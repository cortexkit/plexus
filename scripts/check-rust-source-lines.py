#!/usr/bin/env python3
"""Bound tracked handwritten Rust files, with self-tested, capped exceptions.

Generated Rust declares itself in its first ten lines with an @generated comment,
a generated-by notice, or a generated-file notice containing DO NOT EDIT.
"""

from pathlib import Path, PurePosixPath
import re
import subprocess
import sys
import tempfile


LIMIT = 5_000
EXCEPTIONS = "rust-source-line-exceptions.txt"


def read_exceptions(path):
    exceptions = {}
    for number, row in enumerate(path.read_text().splitlines(), 1):
        if not row.strip() or row.lstrip().startswith("#"):
            continue
        fields = row.split(maxsplit=2)
        if len(fields) != 3:
            raise ValueError(f"{path.name}:{number}: expected path, ceiling, and reason")
        name, ceiling, reason = fields
        relative = PurePosixPath(name)
        if (relative.is_absolute() or ".." in relative.parts
                or relative.as_posix() != name or relative.suffix != ".rs"
                or name in exceptions or not ceiling.isdecimal() or int(ceiling) < 1):
            raise ValueError(f"{path.name}:{number}: invalid or duplicate exception")
        exceptions[name] = (int(ceiling), reason)
    return exceptions


def exempt(name, source):
    path = PurePosixPath(name)
    if (path.name == "tests.rs" or path.name.endswith("_tests.rs")
            or {"tests", "benches", "examples"}.intersection(path.parts[:-1])):
        return True
    header = source.splitlines()[:10]
    return any(
        re.match(rb"\s*(?://|/\*|\*)", line)
        and (re.search(rb"(?<!\w)@generated\b", line)
             or re.search(rb"\bgenerated by\b", line, re.IGNORECASE)
             or (b"generated" in line.lower() and b"do not edit" in line.lower()))
        for line in header
    )


def violations(root, names, exceptions):
    hits = []
    checked = 0
    skipped = 0
    for name in names:
        source = (root / name).read_bytes()
        if name not in exceptions and exempt(name, source):
            skipped += 1
            continue
        checked += 1
        count = source.count(b"\n") + int(bool(source) and not source.endswith(b"\n"))
        ceiling = exceptions.get(name, (LIMIT, ""))[0]
        if count > ceiling:
            hits.append(f"{name}: {count} lines > {ceiling}-line ceiling")
    return hits, checked, skipped


def self_test(root):
    scratch = root / "target" / "scratch"
    scratch.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="rust-source-lines-", dir=scratch) as temporary:
        planted = Path(temporary)

        def check(name, count, exceptions=None, prefix=b""):
            path = planted / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(prefix + b"// planted line\n" * (count - prefix.count(b"\n")))
            return violations(planted, [name], exceptions or {})[0]

        if check("oversized.rs", LIMIT + 1) != [
            "oversized.rs: 5001 lines > 5000-line ceiling"
        ]:
            raise ValueError("oversized-file control was not refused")
        exception_file = planted / EXCEPTIONS
        exception_file.write_text("exception.rs 5100 split in progress\n")
        exceptions = read_exceptions(exception_file)
        if check("exception.rs", 5101, exceptions) != [
            "exception.rs: 5101 lines > 5100-line ceiling"
        ]:
            raise ValueError("grown-exception control was not refused")
        if check("boundary.rs", LIMIT) or check("exception.rs", 5100, exceptions):
            raise ValueError("a file at its ceiling was refused")
        for name in ("area_tests.rs", "tests.rs", "tests/area.rs",
                     "benches/area.rs", "examples/area.rs"):
            if check(name, LIMIT + 1):
                raise ValueError(f"test/example exemption was refused: {name}")
        for prefix in (b"// @generated\n", b"// Code generated by fixture; DO NOT EDIT.\n",
                       b"/* automatically generated by rust-bindgen */\n"):
            if check("generated.rs", LIMIT + 1, prefix=prefix):
                raise ValueError("generated-file exemption was refused")
        partial = planted / "partial.rs"
        partial.write_bytes(b"// line\n" * LIMIT + b"// no trailing newline")
        if not violations(planted, ["partial.rs"], {})[0]:
            raise ValueError("unterminated final line was not counted")
    print("Rust source line controls passed (oversized file and grown exception refused; "
          "boundaries, exemptions, and final line checked)")


def main():
    root = Path(__file__).resolve().parent.parent
    try:
        self_test(root)
        exceptions = read_exceptions(root / "scripts" / EXCEPTIONS)
        tracked = subprocess.check_output(
            ["git", "ls-files", "-z", "--", "*.rs"], cwd=root
        ).decode().split("\0")
        names = sorted(filter(None, tracked))
        if not names:
            raise ValueError("git listed no Rust source files")
        missing = exceptions.keys() - set(names)
        if missing:
            raise ValueError("exceptions are not tracked Rust files: " + ", ".join(sorted(missing)))
        hits, checked, skipped = violations(root, names, exceptions)
        if hits:
            print("refusing: tracked handwritten Rust exceeds its line ceiling", file=sys.stderr)
            print("\n".join(hits), file=sys.stderr)
            return 1
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f"refusing: Rust source line check: {error}", file=sys.stderr)
        return 2
    print(f"Rust source line check passed ({checked} handwritten files; {skipped} exempt; "
          f"{len(exceptions)} capped exceptions; default ceiling {LIMIT})")
    for name, (ceiling, reason) in sorted(exceptions.items()):
        print(f"  exception: {name} <= {ceiling} lines ({reason})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
